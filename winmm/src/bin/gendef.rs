//! Reads the export table of a Windows PE file and writes a module-definition
//! file (port of tools/gendef; see there for the why of both modes).
//!
//!   gendef -in libhl.dll -target libhl_o -out libhl.def [-skip a,b] [-list]
//!   gendef -in winmm.dll -library winmm.dll -stubs winmm_stubs.c -out winmm.def
//!
//! -stubs: per-export C tail-call thunks + an aliasing .def, for a proxy that
//! ships under the same name as the system DLL (forwarders cannot self-name).

use std::collections::{HashMap, HashSet};
use std::fmt::Write as _;
use std::process::exit;

type Res<T> = Result<T, String>;

fn main() {
    if let Err(e) = run() {
        eprintln!("gendef: {e}");
        exit(1);
    }
}

/// Go flag syntax: -name value, -name=value, --name; -list is a bool.
fn parse_flags() -> Res<HashMap<String, String>> {
    let mut m = HashMap::new();
    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        let name = a
            .strip_prefix("--")
            .or_else(|| a.strip_prefix('-'))
            .ok_or(format!("unexpected argument {a:?}"))?;
        let (name, val) = match name.split_once('=') {
            Some(("list", v)) => match v {
                "1" | "t" | "T" | "TRUE" | "true" | "True" => ("list".into(), "true".into()),
                "0" | "f" | "F" | "FALSE" | "false" | "False" => ("list".into(), "false".into()),
                _ => return Err(format!("invalid boolean value {v:?} for -list")),
            },
            Some((n, v)) => (n.to_string(), v.to_string()),
            None if name == "list" => (name.to_string(), "true".to_string()),
            None => (
                name.to_string(),
                args.next()
                    .ok_or(format!("flag needs an argument: -{name}"))?,
            ),
        };
        if !["in", "target", "out", "library", "skip", "stubs", "list"].contains(&name.as_str()) {
            return Err(format!("flag provided but not defined: -{name}"));
        }
        m.insert(name, val);
    }
    Ok(m)
}

fn run() -> Res<()> {
    let f = parse_flags()?;
    let get = |k: &str| f.get(k).map_or("", String::as_str);
    let (input, out) = (get("in"), get("out"));
    if input.is_empty() {
        return Err("-in is required".into());
    }
    let exports = read_exports(input)?;
    if exports.is_empty() {
        return Err(format!("{input}: no named exports"));
    }
    if get("list") == "true" {
        return write(out, &listing(&exports));
    }
    let name = if get("library").is_empty() {
        base_name(input)
    } else {
        get("library")
    };
    let skip = split_names(get("skip"));

    if !get("stubs").is_empty() {
        if let Some(e) = exports
            .iter()
            .find(|e| !skip.contains(e.name.as_str()) && !is_c_ident(&e.name))
        {
            return Err(format!(
                "export {:?} is not a valid C identifier; cannot generate a stub",
                e.name
            ));
        }
        write(get("stubs"), &stub_file(&exports, &skip))?;
        return write(out, &alias_def(name, &exports, &skip));
    }
    if get("target").is_empty() {
        return Err("-target is required".into());
    }
    write(out, &def(name, get("target"), &exports, &skip))
}

fn is_c_ident(s: &str) -> bool {
    !s.is_empty()
        && s.bytes()
            .enumerate()
            .all(|(i, c)| c == b'_' || c.is_ascii_alphabetic() || (i > 0 && c.is_ascii_digit()))
}

fn stub_file(exports: &[Export], skip: &HashSet<&str>) -> String {
    let mut b = String::new();
    b.push_str("/* generated by tools/gendef - do not edit */\n");
    b.push_str("/* per-export tail-call thunks for the winmm proxy; jump through pointers */\n");
    b.push_str("/* the proxy fills from System32\\winmm.dll at load. */\n\n");
    b.push_str("struct mp_export { const char *name; void **slot; };\n\n");
    let kept: Vec<&Export> = exports
        .iter()
        .filter(|e| !skip.contains(e.name.as_str()))
        .collect();
    for e in &kept {
        let n = &e.name;
        let _ = writeln!(b, "void *mpp_{n};");
        let _ = writeln!(
            b,
            "__attribute__((naked)) void mp_{n}(void){{ __asm__(\"jmp *mpp_{n}(%rip)\"); }}"
        );
    }
    b.push_str("\nconst struct mp_export mp_exports[] = {\n");
    for e in &kept {
        let _ = writeln!(b, "\t{{\"{0}\", &mpp_{0}}},", e.name);
    }
    b.push_str("};\n");
    let _ = writeln!(b, "const unsigned mp_exports_count = {};", kept.len());
    b
}

fn alias_def(library: &str, exports: &[Export], skip: &HashSet<&str>) -> String {
    let mut b = format!("; generated by tools/gendef - do not edit\nLIBRARY {library}\nEXPORTS\n");
    for e in exports.iter().filter(|e| !skip.contains(e.name.as_str())) {
        let _ = writeln!(b, "    {0} = mp_{0} @{1}", e.name, e.ordinal);
    }
    b
}

fn def(library: &str, target: &str, exports: &[Export], skip: &HashSet<&str>) -> String {
    let mut b = format!("; generated by tools/gendef - do not edit\nLIBRARY {library}\nEXPORTS\n");
    for e in exports {
        if skip.contains(e.name.as_str()) {
            let _ = writeln!(b, "    {} @{}", e.name, e.ordinal);
        } else {
            let _ = writeln!(b, "    {0} = {target}.{0} @{1}", e.name, e.ordinal);
        }
    }
    b
}

fn listing(exports: &[Export]) -> String {
    exports.iter().fold(String::new(), |mut b, e| {
        let _ = writeln!(b, "{}\t{}", e.ordinal, e.name);
        b
    })
}

fn write(path: &str, text: &str) -> Res<()> {
    if path.is_empty() {
        use std::io::Write;
        return std::io::stdout()
            .write_all(text.as_bytes())
            .map_err(|e| e.to_string());
    }
    std::fs::write(path, text).map_err(|e| format!("open {path}: {e}"))
}

fn split_names(s: &str) -> HashSet<&str> {
    s.split(',')
        .map(str::trim)
        .filter(|p| !p.is_empty())
        .collect()
}

fn base_name(path: &str) -> &str {
    path.rsplit(['\\', '/']).next().unwrap_or(path)
}

/// One named entry of a PE export directory.
struct Export {
    name: String,
    ordinal: u32,
}

/// A PE file's sections: (virtual address, virtual size, raw data).
struct Image<'a> {
    sections: Vec<(u32, u32, &'a [u8])>,
}

fn u16_at(b: &[u8], off: usize) -> Res<u16> {
    b.get(off..off + 2)
        .map(|s| u16::from_le_bytes([s[0], s[1]]))
        .ok_or("truncated PE header".into())
}

fn u32_at(b: &[u8], off: usize) -> Res<u32> {
    b.get(off..off + 4)
        .map(|s| u32::from_le_bytes([s[0], s[1], s[2], s[3]]))
        .ok_or("truncated PE header".into())
}

impl Image<'_> {
    /// The section bytes starting at rva.
    fn at(&self, rva: u32) -> Res<&[u8]> {
        for &(va, vsize, data) in &self.sections {
            if rva < va || rva >= va.wrapping_add(vsize) {
                continue;
            }
            return data
                .get((rva - va) as usize..)
                .filter(|d| !d.is_empty())
                .ok_or(format!("rva {rva:#x} past raw data"));
        }
        Err(format!("rva {rva:#x} is in no section"))
    }
    fn u32(&self, rva: u32) -> Res<u32> {
        u32_at(self.at(rva)?, 0).map_err(|_| format!("truncated read at rva {rva:#x}"))
    }
    fn u16(&self, rva: u32) -> Res<u16> {
        u16_at(self.at(rva)?, 0).map_err(|_| format!("truncated read at rva {rva:#x}"))
    }
    fn cstring(&self, rva: u32) -> Res<String> {
        let b = self.at(rva)?;
        let end = b
            .iter()
            .position(|&c| c == 0)
            .ok_or(format!("unterminated string at rva {rva:#x}"))?;
        String::from_utf8(b[..end].to_vec())
            .map_err(|_| format!("non-UTF-8 export name at rva {rva:#x}"))
    }
}

/// The named exports of a PE file, sorted by ordinal (IMAGE_EXPORT_DIRECTORY
/// at data directory 0, walked by hand).
fn read_exports(path: &str) -> Res<Vec<Export>> {
    let file = std::fs::read(path).map_err(|e| format!("open {path}: {e}"))?;
    let f = &file[..];
    if f.get(..2) != Some(b"MZ") {
        return Err(format!("{path}: not a PE file"));
    }
    let pe = u32_at(f, 0x3c)? as usize;
    if f.get(pe..pe + 4) != Some(b"PE\0\0") {
        return Err(format!("{path}: not a PE file"));
    }
    let coff = pe + 4;
    let nsections = u16_at(f, coff + 2)? as usize;
    let opt_size = u16_at(f, coff + 16)? as usize;
    let opt = coff + 20;
    // PE32 / PE32+: NumberOfRvaAndSizes, then the data directories.
    let (nrva_off, dirs) = match u16_at(f, opt)? {
        0x10b => (92, 96),
        0x20b => (108, 112),
        _ => return Err(format!("{path}: no optional header")),
    };
    let (va, size) = if opt_size >= dirs + 8 && u32_at(f, opt + nrva_off)? > 0 {
        (u32_at(f, opt + dirs)?, u32_at(f, opt + dirs + 4)?)
    } else {
        (0, 0)
    };
    if va == 0 || size == 0 {
        return Err(format!("{path}: no export directory"));
    }
    let mut sections = Vec::with_capacity(nsections);
    for i in 0..nsections {
        let s = opt + opt_size + 40 * i;
        let (vsize, sva) = (u32_at(f, s + 8)?, u32_at(f, s + 12)?);
        let (raw_size, raw_ptr) = (u32_at(f, s + 16)? as usize, u32_at(f, s + 20)? as usize);
        // No raw data (PointerToRawData 0) = uninitialized section, as debug/pe.
        let raw = if raw_ptr == 0 {
            0..0
        } else {
            raw_ptr..raw_ptr + raw_size
        };
        let data = f
            .get(raw)
            .ok_or(format!("{path}: section {i} past end of file"))?;
        sections.push((sva, vsize, data));
    }
    if sections.is_empty() {
        return Err("no sections".into());
    }
    let m = Image { sections };
    let base = m.u32(va + 16)?;
    let name_count = m.u32(va + 24)?;
    let names_rva = m.u32(va + 32)?;
    let ords_rva = m.u32(va + 36)?;
    let mut out = Vec::with_capacity(name_count as usize);
    for i in 0..name_count {
        let name = m.cstring(m.u32(names_rva + i * 4)?)?;
        let ord = m.u16(ords_rva + i * 2)?;
        out.push(Export {
            name,
            ordinal: base + u32::from(ord),
        });
    }
    out.sort_by_key(|e| e.ordinal);
    Ok(out)
}
