//! Generates the winmm forwarding table from this machine's System32\winmm.dll:
//! one naked tail-jump thunk per export, exported under the same name (or the
//! same NONAME ordinal), jumping through a slot that `dll::bind_forwards` fills
//! from the real DLL. A PE forwarder string cannot name its own module, hence
//! thunks.

use std::fmt::Write as _;
use std::path::PathBuf;

#[path = "src/pe.rs"]
mod pe;

fn main() {
    let root = std::env::var_os("SystemRoot").unwrap_or_else(|| r"C:\Windows".into());
    let sys = PathBuf::from(root).join(r"System32\winmm.dll");
    println!("cargo:rerun-if-changed={}", sys.display());
    println!("cargo:rerun-if-changed=src/pe.rs");
    let image = std::fs::read(&sys).unwrap_or_else(|e| panic!("{}: {e}", sys.display()));
    let exports = pe::exports(&image).unwrap_or_else(|e| panic!("{}: {e}", sys.display()));

    let n = exports.len();
    let mut b = String::from("// generated by build.rs from System32\\winmm.dll - do not edit\n");
    let _ = writeln!(
        b,
        "static SLOTS: [AtomicPtr<c_void>; {n}] = [const {{ AtomicPtr::new(null_mut()) }}; {n}];"
    );
    // GetProcAddress keys: Some(name) or the ordinal of a NONAME export.
    let _ = writeln!(b, "static PROCS: [(Option<&CStr>, u16); {n}] = [");
    for e in &exports {
        let key = e
            .name
            .as_ref()
            .map_or("None".into(), |s| format!("Some(c{s:?})"));
        let _ = writeln!(b, "    ({key}, {}),", e.ordinal);
    }
    b.push_str("];\n");
    for (i, e) in exports.iter().enumerate() {
        let off = i * 8;
        if let Some(name) = &e.name {
            assert!(
                !name.is_empty() && name.bytes().all(|c| c == b'_' || c.is_ascii_alphanumeric()),
                "export {name:?} is not a plain symbol name"
            );
            let _ = writeln!(
                    b,
                    "#[unsafe(naked)]\n#[unsafe(export_name = {name:?})]\nextern \"system\" fn fwd_{i}() {{\n    core::arch::naked_asm!(\"jmp qword ptr [rip + {{s}} + {off}]\", s = sym SLOTS);\n}}"
                );
        } else {
            // Not a Rust item: rustc would export it by name. The linker
            // exports the label by ordinal only.
            let sym = format!("winmm_noname_{}", e.ordinal);
            let _ = writeln!(
                    b,
                    "core::arch::global_asm!(\".globl {sym}\", \"{sym}:\", \"jmp qword ptr [rip + {{s}} + {off}]\", s = sym SLOTS);"
                );
            println!(
                "cargo:rustc-cdylib-link-arg=/EXPORT:{sym},@{},NONAME",
                e.ordinal
            );
        }
    }
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("forwards.rs");
    std::fs::write(&out, b).unwrap_or_else(|e| panic!("{}: {e}", out.display()));
}
